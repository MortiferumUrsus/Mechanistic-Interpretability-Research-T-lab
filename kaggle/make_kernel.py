def _find_payload(root, max_depth=4):
    # Locate the payload by STRUCTURE, not by name. Mount layout is not stable across Kaggle
    # images: the same dataset appears either as /kaggle/input/<slug> or nested as
    # /kaggle/input/datasets/<owner>/<slug>. Matching on the presence of src/ + configs/ works
    # under both layouts and survives a rename.
    if not root.exists():
        return None
    stack = [(root, 0)]
    while stack:
        d, depth = stack.pop(0)
        try:
            kids = sorted(p for p in d.iterdir() if p.is_dir())
        except OSError:
            continue
        names = {p.name for p in kids}
        if {"src", "configs"} <= names:
            return d
        if depth < max_depth:
            stack.extend((p, depth + 1) for p in kids)
    return None


