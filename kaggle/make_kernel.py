def cell(source: str, kind: str = "code") -> dict:
    lines = source.splitlines(keepends=True)
    if kind == "markdown":
        return {"cell_type": "markdown", "metadata": {}, "source": lines}
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": lines}


def resolve_queue(value: str) -> list[str]:
    p = Path(value)
    if p.is_file():
        text = p.read_text(encoding="utf-8")
        line = next((l.strip() for l in text.splitlines() if l.strip() and not l.strip().startswith("#")), "")
        value = line
    items = [x.strip() for x in value.split(",") if x.strip()]
    if not items:
        raise SystemExit(f"empty queue (from {value!r})")
    return items


def env_cell(env: list[str] | None) -> str:
    """One tiny cell exporting KEY=VALUE overrides (e.g. TLAB_LAYER=10) before any stage runs.

    Subprocesses inherit the notebook's environment, so this is how a driver that reads its
    configuration from the environment (run_layer.py) is parameterised without the queue runner
    having to know any extra flags.
    """
    lines = ["import os"]
    for item in env or []:
        k, _, v = item.partition("=")
        lines.append(f"os.environ[{k!r}] = {v!r}")
    lines.append(f"print('env overrides:', {list(env or [])!r})")
    return chr(10).join(lines) + chr(10)


def build_notebook(name: str, queue: list[str], skip_data_restore: bool, env: list[str] | None = None) -> dict:
    queue_literal = json.dumps(queue)
    intro = (
        INTRO.replace("{NAME}", name)
        .replace("{QUEUE_DISPLAY}", ", ".join(queue))
        .replace("{DATA_RESTORE_DISPLAY}", "SKIPPED (--skip-data-restore)" if skip_data_restore else "enabled")
    )
    data_restore = DATA_RESTORE.replace("__SKIP_DATA_RESTORE__", "True" if skip_data_restore else "False")
    queue_exec = QUEUE_EXEC.replace("__QUEUE_LITERAL__", queue_literal)
    collect = (
        COLLECT.replace("__SMALL_DATA_LITERAL__", json.dumps(SMALL_DATA_NAMES))
        .replace("__OVERSIZE_LIMIT_BYTES__", str(OVERSIZE_LIMIT_BYTES))
        .replace("__SESSION_LIMIT_HOURS__", str(SESSION_LIMIT_HOURS))
    )
    return {
        "cells": [
            cell(intro, "markdown"),
            cell(PIP_INSTALL),
            cell(env_cell(env)),
            cell(SETUP.replace("__DATASET_ID__", DATASET_ID)),
            cell(data_restore),
            cell(queue_exec),
            cell(collect),
        ],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.10"},
            "accelerator": "GPU",
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def build_kernel_metadata(name: str) -> dict:
    return {
        "id": f"{USERNAME}/{name}",
        "title": name,
        "code_file": f"{name}.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [DATASET_ID],
        "competition_sources": [],
        "kernel_sources": [],
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="kernel slug, e.g. tlab-mi-smoke")
    ap.add_argument("--queue", required=True,
                    help="comma list of driver:stage items, or a path to a queue file with one such line")
    ap.add_argument("--out", type=Path, required=True, help="directory to write <name>.ipynb + kernel-metadata.json")
    ap.add_argument("--env", action="append", default=[], help="KEY=VALUE exported inside the notebook before any stage (repeatable)")
    ap.add_argument("--skip-data-restore", action="store_true",
                    help="bake the notebook to skip rebuilding data/acts.f16 (use for queues that need no heavy dump)")
    args = ap.parse_args()

    queue = resolve_queue(args.queue)
    nb = build_notebook(args.name, queue, args.skip_data_restore, args.env)
    meta = build_kernel_metadata(args.name)

    args.out.mkdir(parents=True, exist_ok=True)
    nb_path = args.out / f"{args.name}.ipynb"
    meta_path = args.out / "kernel-metadata.json"
    nb_path.write_text(json.dumps(nb, indent=1), encoding="utf-8")
    meta_path.write_text(json.dumps(meta, indent=1), encoding="utf-8")

    print(f"wrote {nb_path} ({nb_path.stat().st_size / 1024:.1f} KB)")
    print(f"wrote {meta_path}")
    print(f"queue ({len(queue)} items): {queue}")
    print(f"skip_data_restore={args.skip_data_restore}")


if __name__ == "__main__":
    main()
